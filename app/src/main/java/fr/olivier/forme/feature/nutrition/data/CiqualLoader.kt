package fr.olivier.forme.feature.nutrition.data

import android.content.Context
import androidx.datastore.core.DataStore
import androidx.datastore.preferences.core.Preferences
import androidx.datastore.preferences.core.edit
import androidx.datastore.preferences.core.stringPreferencesKey
import androidx.room.withTransaction
import dagger.hilt.android.qualifiers.ApplicationContext
import fr.olivier.forme.core.db.FormeDatabase
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.withContext
import java.io.InputStream
import javax.inject.Inject
import javax.inject.Singleton

/**
 * Loads the embedded Ciqual table (assets/ciqual.tsv, generated by tools/ciqual/convert.py) into Room.
 * Runs once per dataset version; a new table in a future release reloads it automatically.
 */
@Singleton
class CiqualLoader @Inject constructor(
    private val db: FormeDatabase,
    private val dataStore: DataStore<Preferences>,
    @ApplicationContext private val context: Context,
) {
    suspend fun ensureLoaded() = withContext(Dispatchers.IO) {
        val dao = db.ciqualDao()
        if (dataStore.data.first()[LOADED_VERSION] == DATASET_VERSION && dao.count() > 0) return@withContext
        val foods = context.assets.open(ASSET).use(::parse)
        db.withTransaction {
            dao.deleteAll()
            foods.chunked(500).forEach { dao.insertAll(it) }
        }
        dataStore.edit { it[LOADED_VERSION] = DATASET_VERSION }
    }

    companion object {
        const val ASSET = "ciqual.tsv"
        /** Ciqual release embedded in the APK. */
        const val DATASET_VERSION = "2025-11-03"
        private val LOADED_VERSION = stringPreferencesKey("ciqual_dataset_version")

        fun parse(input: InputStream): List<CiqualFoodEntity> =
            input.bufferedReader().lineSequence().drop(1).filter { it.isNotBlank() }.mapNotNull { line ->
                val f = line.split('\t')
                if (f.size < 7) return@mapNotNull null
                CiqualFoodEntity(
                    code = f[0].toLongOrNull() ?: return@mapNotNull null,
                    name = f[1],
                    groupName = f[2],
                    kcalPer100g = f[3].toDoubleOrNull(),
                    proteinPer100g = f[4].toDoubleOrNull(),
                    carbsPer100g = f[5].toDoubleOrNull(),
                    fatPer100g = f[6].toDoubleOrNull(),
                )
            }.toList()
    }
}
